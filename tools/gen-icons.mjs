// Builds shell/common/icons.js from lucide-static, the icon set Bloom uses
// through lucide-react. Usage: node tools/gen-icons.mjs [--check]
import { readFileSync, writeFileSync } from "node:fs";

const ICONS = [
	"sun", "moon", "cloud", "cloud-fog", "cloud-drizzle", "cloud-rain", "cloud-snow", "cloud-lightning", "thermometer",
	"cpu", "memory-stick", "hard-drive", "arrow-up-down", "search", "sliders-horizontal",
	"chevron-left", "chevron-right", "x", "wifi", "wifi-off", "bluetooth", "volume-2",
	"calendar-days", "timer", "folder", "usb", "mic", "screen-share", "bell-off", "bell", "rotate-ccw", "lock-keyhole", "monitor-smartphone", "laptop",
	"loader-circle", "refresh-cw", "plus", "bell-ring"
];

const root = new URL("../", import.meta.url);
const lucide = new URL("tools/node_modules/lucide-static/", root);
const version = JSON.parse(readFileSync(new URL("package.json", lucide), "utf8")).version;

const entries = ICONS.map(name => {
	const raw = readFileSync(new URL(`icons/${name}.svg`, lucide), "utf8");
	const svg = raw.replace(/<!--[\s\S]*?-->/g, "").replace(/\s*\n\s*/g, " ").replace(/>\s+</g, "><").trim();
	return `\t${JSON.stringify(name)}: ${JSON.stringify(svg)}`;
});

// Lucide icons Bloom draws with fill="currentColor" (the timer's Play/Pause,
// the battery hub's charging bolt).
for (const name of ["play", "pause", "zap"]) {
	const raw = readFileSync(new URL(`icons/${name}.svg`, lucide), "utf8");
	const svg = raw.replace(/<!--[\s\S]*?-->/g, "").replace(/\s*\n\s*/g, " ").replace(/>\s+</g, "><").trim().replace('fill="none"', 'fill="currentColor"');
	entries.push(`\t${JSON.stringify(name + "-filled")}: ${JSON.stringify(svg)}`);
}

// Bloom's player icons (filled SF Symbols drawings), see third_party/bloom-sf-symbols/NOTICE.md.
const SF = [
	"play.fill", "pause.fill", "backward.fill", "forward.fill", "music.note", "headphones",
	"speaker.wave.1.fill", "speaker.wave.2.fill", "speaker.wave.3.fill", "speaker.slash.fill", "slider.horizontal.3"
];
for (const name of SF) {
	const raw = readFileSync(new URL(`third_party/bloom-sf-symbols/${name}.svg`, root), "utf8");
	const svg = raw.replace(/<!--[\s\S]*?-->/g, "").replace(/\s*\n\s*/g, " ").replace(/>\s+</g, "><").trim();
	entries.push(`\t${JSON.stringify("sf-" + name)}: ${JSON.stringify(svg)}`);
}

// Bloom's own Command Center icons, see third_party/bloom-icons/README.md.
const BLOOM = [
	"wifi", "bluetooth", "dock", "notch", "moon", "battery-saver", "tray", "bell", "settings", "reload", "brightness-low", "sun"
];
for (const name of BLOOM) {
	const raw = readFileSync(new URL(`third_party/bloom-icons/${name}.svg`, root), "utf8");
	entries.push(`\t${JSON.stringify("bloom-" + name)}: ${JSON.stringify(raw.trim())}`);
}

const out = `// Generated by tools/gen-icons.mjs from lucide-static ${version} (ISC licence,
// see licenses/lucide.txt), Bloom's player icons (third_party/bloom-sf-symbols,
// see its NOTICE.md) and Bloom's own icons (third_party/bloom-icons). Do not
// edit by hand.

var svg = {
${entries.join(",\n")}
};
`;

const target = new URL("shell/common/icons.js", root);
if (process.argv.includes("--check")) {
	let current = "";
	try { current = readFileSync(target, "utf8"); } catch {}
	if (current !== out) {
		console.error("shell/common/icons.js is out of date; run: node tools/gen-icons.mjs");
		process.exit(1);
	}
	console.log("ok");
} else {
	writeFileSync(target, out);
	console.log(`wrote shell/common/icons.js (${entries.length} icons)`);
}
