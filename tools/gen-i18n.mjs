// Builds shell/common/i18n/catalogs.js from Bloom's catalogs (shell/i18n/locales)
// and the Linux overlay (shell/i18n/linux), for QML's I18n.
// Usage: node tools/gen-i18n.mjs [--check]
import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";

const root = new URL("../", import.meta.url);
const read = path => JSON.parse(readFileSync(new URL(path, root), "utf8"));
const locales = readdirSync(new URL("shell/i18n/locales/", root)).filter(n => n.endsWith(".json")).map(n => n.slice(0, -5)).sort();
const catalogs = {};
for (const lang of locales) {
	const catalog = read(`shell/i18n/locales/${lang}.json`);
	const overlay = new URL(`shell/i18n/linux/${lang}.json`, root);
	if (existsSync(overlay))
		catalog.linux = read(`shell/i18n/linux/${lang}.json`).linux || {};
	catalogs[lang] = catalog;
}
const source = readFileSync(new URL("shell/i18n/SOURCE", root), "utf8").trim();
const out = `.pragma library
// Generated by tools/gen-i18n.mjs from shell/i18n (Bloom ${source.split(" ")[0]} and the
// Linux overlay). Do not edit by hand.

var catalogs = ${JSON.stringify(catalogs, null, "\t")};
`;
const target = new URL("shell/common/i18n/catalogs.js", root);
if (process.argv.includes("--check")) {
	const current = existsSync(target) ? readFileSync(target, "utf8") : "";
	if (current !== out) {
		console.error("shell/common/i18n/catalogs.js is out of date; run: node tools/gen-i18n.mjs");
		process.exit(1);
	}
	console.log("ok");
} else {
	writeFileSync(target, out);
	console.log(`wrote shell/common/i18n/catalogs.js (${locales.join(", ")})`);
}
