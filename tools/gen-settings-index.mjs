// Builds shell/settings/search-index.js, the list Settings' search looks through,
// from the rows themselves so it can't go stale. Usage: node tools/gen-settings-index.mjs [--check]
import { readFileSync, writeFileSync } from "node:fs";

const root = new URL("../shell/settings/", import.meta.url);
const TABS = { GeneralTab: "general", AppearanceTab: "appearance", NotchTab: "notch", DockTab: "dock", OverlaysTab: "overlays", AboutTab: "about" };
const rows = [];
const LABEL = /\blabel: "([^"]+)"/g;

for (const [file, tab] of Object.entries(TABS)) {
	for (const m of readFileSync(new URL(file + ".qml", root), "utf8").matchAll(LABEL)) rows.push({ label: m[1], tab });
}
const pages = readFileSync(new URL("SystemPages.qml", root), "utf8").split(/pageId: "/).slice(1);
for (const page of pages) {
	const tab = page.slice(0, page.indexOf('"'));
	for (const m of page.matchAll(LABEL)) rows.push({ label: m[1], tab });
}
for (const [tab, labels] of Object.entries({ network: ["Wi-Fi", "Scan Again", "Networks"], bluetooth: ["Bluetooth", "My Devices", "Add a Device"] })) {
	for (const label of labels) rows.push({ label, tab });
}
const seen = new Set();
const unique = rows.filter(r => !/^(Dark|Light|Fixed|Smart|Peek|Off|On|Left|Right)\b/.test(r.label) && !seen.has(r.tab + r.label) && seen.add(r.tab + r.label));
const out = "// Generated by tools/gen-settings-index.mjs. Do not edit by hand.\nvar ROWS = " + JSON.stringify(unique, null, "\t") + ";\n";
const target = new URL("search-index.js", root);
if (process.argv.includes("--check")) {
	if (readFileSync(target, "utf8") !== out) {
		console.error("search-index.js is out of date; run: node tools/gen-settings-index.mjs");
		process.exit(1);
	}
	console.log("ok");
} else {
	writeFileSync(target, out);
	console.log(`wrote shell/settings/search-index.js (${unique.length} rows)`);
}
