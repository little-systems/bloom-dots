#!/usr/bin/env python3
"""Builds shell/modules/launcher/emoji-data.js from Python's Unicode names:
every emoji code point in the blocks a desktop draws in colour. Usage:
python3 tools/gen-emoji.py"""
import json
import pathlib
import unicodedata

RANGES = [(0x1F300, 0x1F64F), (0x1F680, 0x1F6FF), (0x1F90C, 0x1F9FF), (0x1FA70, 0x1FAFF), (0x2600, 0x26FF), (0x2700, 0x27BF)]
out = []
for lo, hi in RANGES:
	for code in range(lo, hi + 1):
		char = chr(code)
		name = unicodedata.name(char, "")
		if name and not 0x1F3FB <= code <= 0x1F3FF:
			out.append([char, name.capitalize()])
path = pathlib.Path(__file__).parent.parent / "shell/modules/launcher/emoji-data.js"
path.write_text("// Generated by tools/gen-emoji.py.\nvar EMOJI = " + json.dumps(out, ensure_ascii=False, separators=(",", ":")) + ";\n")
print(len(out), "emoji")
